public class Author
{
    //Instance variables
    String name;
    String birthday;

    //Constructors
    public Author(String n, String bd) {
        name = n;
        birthday = bd;
    } 

    //Getter methods
    public String getName() {
        return name;
    }

    public String getBirth() {
        return birthday;
    }

}
